-- 3) Create an INTEGER id and move PK to it (keep the old text id as 'id_legacy')
--    Works whether current id is text or int.
ALTER TABLE organizations
  ADD COLUMN IF NOT EXISTS id_int BIGINT GENERATED BY DEFAULT AS IDENTITY;

-- For numeric-looking legacy ids, preserve value; otherwise keep generated
UPDATE organizations
SET id_int = CASE
  WHEN id::text ~ '^[0-9]+$' THEN (id::text)::bigint
  ELSE id_int
END;

-- Not null & PK swap
ALTER TABLE organizations ALTER COLUMN id_int SET NOT NULL;
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.table_constraints
    WHERE table_name='organizations' AND constraint_type='PRIMARY KEY'
  ) THEN
    ALTER TABLE organizations DROP CONSTRAINT organizations_pkey;
  END IF;
END $$;
ALTER TABLE organizations ADD CONSTRAINT organizations_pkey PRIMARY KEY (id_int);

-- Keep old id for audit, switch app to integer id
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name='organizations' AND column_name='id_legacy'
  ) THEN
    ALTER TABLE organizations RENAME COLUMN id TO id_legacy;
  END IF;
END $$;
ALTER TABLE organizations RENAME COLUMN id_int TO id;

-- Avoid picking legacy string-id rows by name in the future
UPDATE organizations
SET name = name || ' [legacy string-id — ignore]'
WHERE id_legacy IS NOT NULL AND id_legacy::text !~ '^[0-9]+$'
  AND name NOT LIKE '%[legacy string-id — ignore]%';

